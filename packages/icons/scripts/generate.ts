import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  generateComponent,
  generateNativeComponent,
  iconMetaSchema,
  imageMetaSchema,
  processSvg,
  readPngSize,
  toComponentName,
  toImageExportName,
  type IconMeta,
  type ImageMeta,
} from '@icon-studio/core'

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconsDir = process.env.ICONS_DIR ?? join(packageDir, '../../icons')
const imagesDir = process.env.IMAGES_DIR ?? join(packageDir, '../../images')
const outDir = join(packageDir, 'src/generated')

const header =
  '// Generated by scripts/generate.ts from the icons/ and images/ folders. Do not edit.'

function loadIcons(): IconMeta[] {
  const metas = readdirSync(iconsDir)
    .filter((file) => file.endsWith('.json'))
    .map((file) => {
      const parsed = iconMetaSchema.safeParse(
        JSON.parse(readFileSync(join(iconsDir, file), 'utf8'))
      )
      if (!parsed.success) {
        throw new Error(`icons/${file}: ${parsed.error.issues.map((i) => i.message).join(', ')}`)
      }
      if (`${parsed.data.slug}.json` !== file) {
        throw new Error(`icons/${file}: slug "${parsed.data.slug}" does not match the file name`)
      }
      return parsed.data
    })
    .sort((a, b) => a.slug.localeCompare(b.slug))

  const seen = new Map<string, string>()
  for (const meta of metas) {
    const componentName = toComponentName(meta.slug)
    const other = seen.get(componentName)
    if (other) throw new Error(`"${meta.slug}" and "${other}" both become ${componentName}`)
    seen.set(componentName, meta.slug)
  }

  const orphans = readdirSync(iconsDir)
    .filter((file) => file.endsWith('.svg'))
    .filter((file) => !metas.some((meta) => `${meta.slug}.svg` === file))
  if (orphans.length) console.warn(`Skipping SVGs without metadata: ${orphans.join(', ')}`)

  return metas
}

const metas = loadIcons()
rmSync(outDir, { recursive: true, force: true })
mkdirSync(join(outDir, 'icons'), { recursive: true })
mkdirSync(join(outDir, 'native'), { recursive: true })

for (const meta of metas) {
  const raw = readFileSync(join(iconsDir, `${meta.slug}.svg`), 'utf8')
  const { root } = processSvg(raw, meta.slug)
  writeFileSync(join(outDir, 'icons', `${meta.slug}.tsx`), generateComponent(root, meta))
  const native = generateNativeComponent(root, meta)
  writeFileSync(join(outDir, 'native', `${meta.slug}.tsx`), native.code)
  if (native.skipped.length) {
    console.warn(
      `${meta.slug}: react-native-svg can't render <${native.skipped.join('>, <')}>; left out of the native component`
    )
  }
}

const entries = metas.map((meta) => ({ meta, componentName: toComponentName(meta.slug) }))

writeFileSync(
  join(outDir, 'index.ts'),
  [
    header,
    ...entries.flatMap(({ meta, componentName }) => [
      `export { ${componentName} } from './icons/${meta.slug}.js'`,
      ...(meta.colorProps.length
        ? [`export type { ${componentName}Props } from './icons/${meta.slug}.js'`]
        : []),
    ]),
    '',
  ].join('\n')
)

writeFileSync(
  join(outDir, 'dynamic.tsx'),
  [
    header,
    "import type { ReactNode } from 'react'",
    "import type { IconProps } from '../types.js'",
    ...entries.map(
      ({ meta, componentName }) => `import { ${componentName} } from './icons/${meta.slug}.js'`
    ),
    '',
    'export const icons = {',
    ...entries.map(
      ({ meta, componentName }) => `  ${JSON.stringify(meta.slug)}: ${componentName},`
    ),
    '} as const',
    '',
    'export type IconName = keyof typeof icons',
    '',
    'export const iconNames = Object.keys(icons) as IconName[]',
    '',
    'export function isIconName(value: string): value is IconName {',
    '  return Object.hasOwn(icons, value)',
    '}',
    '',
    'export interface IconByNameProps extends IconProps {',
    '  name: IconName | (string & {})',
    '  fallback?: ReactNode',
    '}',
    '',
    'export function Icon({ name, fallback = null, ...props }: IconByNameProps) {',
    '  if (!isIconName(name)) return fallback',
    '  const Component = icons[name]',
    '  return <Component {...props} />',
    '}',
    '',
  ].join('\n')
)

const manifest = metas.map(({ name, slug, tags, mode, defaults, colorProps }) => ({
  name,
  slug,
  componentName: toComponentName(slug),
  tags,
  mode,
  defaultSize: defaults.size,
  colorProps: colorProps.map((prop) => prop.name),
}))

writeFileSync(
  join(outDir, 'native.tsx'),
  [
    header,
    "import type { ReactNode } from 'react'",
    "import type { NativeIconProps } from '../native_types.js'",
    ...entries.map(
      ({ meta, componentName }) => `import { ${componentName} } from './native/${meta.slug}.js'`
    ),
    '',
    ...entries.map(({ componentName }) => `export { ${componentName} }`),
    ...entries
      .filter(({ meta }) => meta.colorProps.length)
      .map(
        ({ meta, componentName }) =>
          `export type { ${componentName}Props } from './native/${meta.slug}.js'`
      ),
    '',
    'export const icons = {',
    ...entries.map(
      ({ meta, componentName }) => `  ${JSON.stringify(meta.slug)}: ${componentName},`
    ),
    '} as const',
    '',
    'export type IconName = keyof typeof icons',
    '',
    'export const iconNames = Object.keys(icons) as IconName[]',
    '',
    'export function isIconName(value: string): value is IconName {',
    '  return Object.hasOwn(icons, value)',
    '}',
    '',
    'export interface IconByNameProps extends NativeIconProps {',
    '  name: IconName | (string & {})',
    '  fallback?: ReactNode',
    '}',
    '',
    'export function Icon({ name, fallback = null, ...props }: IconByNameProps) {',
    '  if (!isIconName(name)) return fallback',
    '  const Component = icons[name]',
    '  return <Component {...props} />',
    '}',
    '',
  ].join('\n')
)

const images = loadImages()
mkdirSync(join(outDir, 'png'), { recursive: true })
for (const image of images) {
  copyFileSync(join(imagesDir, `${image.slug}.png`), join(outDir, 'png', `${image.slug}.png`))
}

writeFileSync(
  join(outDir, 'images.ts'),
  [
    header,
    "import type { ImageAsset } from '../types.js'",
    ...images.map(
      (image) => `import ${toImageExportName(image.slug)}Png from './png/${image.slug}.png'`
    ),
    '',
    ...images.map((image) => {
      const exportName = toImageExportName(image.slug)
      return `export const ${exportName}: ImageAsset = ${exportName}Png`
    }),
    '',
  ].join('\n')
)

writeFileSync(
  join(outDir, 'native-images.ts'),
  [
    header,
    "import type { NativeImageSource } from '../native_types.js'",
    ...images.map(
      (image) => `import ${toImageExportName(image.slug)}Png from './png/${image.slug}.png'`
    ),
    '',
    ...images.map((image) => {
      const exportName = toImageExportName(image.slug)
      return `export const ${exportName} = ${exportName}Png as unknown as NativeImageSource`
    }),
    '',
  ].join('\n')
)

const imageManifest = images.map(({ name, slug, tags, alt, width, height, bytes }) => ({
  name,
  slug,
  exportName: toImageExportName(slug),
  tags,
  alt,
  width,
  height,
  bytes,
}))

writeFileSync(
  join(outDir, 'manifest.ts'),
  [
    header,
    'export interface IconManifestEntry {',
    '  name: string',
    '  slug: string',
    '  componentName: string',
    '  tags: string[]',
    "  mode: 'mono' | 'multi'",
    '  defaultSize: number',
    '  colorProps: string[]',
    '}',
    '',
    'export interface ImageManifestEntry {',
    '  name: string',
    '  slug: string',
    '  exportName: string',
    '  tags: string[]',
    '  alt: string',
    '  width: number',
    '  height: number',
    '  bytes: number',
    '}',
    '',
    `export const iconManifest: IconManifestEntry[] = ${JSON.stringify(manifest, null, 2)}`,
    '',
    `export const imageManifest: ImageManifestEntry[] = ${JSON.stringify(imageManifest, null, 2)}`,
    '',
  ].join('\n')
)

console.log(
  `Generated ${metas.length} icon component(s) and ${images.length} image(s) in src/generated`
)

function loadImages(): ImageMeta[] {
  if (!existsSync(imagesDir)) return []
  const files = readdirSync(imagesDir)
  const seen = new Map<string, string>()
  const result = files
    .filter((file) => file.endsWith('.json'))
    .map((file) => {
      const parsed = imageMetaSchema.safeParse(
        JSON.parse(readFileSync(join(imagesDir, file), 'utf8'))
      )
      if (!parsed.success) {
        throw new Error(`images/${file}: ${parsed.error.issues.map((i) => i.message).join(', ')}`)
      }
      const meta = parsed.data
      if (`${meta.slug}.json` !== file) {
        throw new Error(`images/${file}: slug "${meta.slug}" does not match the file name`)
      }
      const pngPath = join(imagesDir, `${meta.slug}.png`)
      if (!existsSync(pngPath)) throw new Error(`images/${meta.slug}.png is missing`)
      const bytes = readFileSync(pngPath)
      const size = readPngSize(bytes)
      const exportName = toImageExportName(meta.slug)
      const other = seen.get(exportName)
      if (other) throw new Error(`"${meta.slug}" and "${other}" both become ${exportName}`)
      seen.set(exportName, meta.slug)
      return { ...meta, ...size, bytes: bytes.byteLength }
    })
    .sort((a, b) => a.slug.localeCompare(b.slug))
  const orphans = files
    .filter((file) => file.endsWith('.png'))
    .filter((file) => !result.some((meta) => `${meta.slug}.png` === file))
  if (orphans.length) console.warn(`Skipping PNGs without metadata: ${orphans.join(', ')}`)
  return result
}
